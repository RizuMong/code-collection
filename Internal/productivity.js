function isSameEmployee(assignment, employeeEmail) {
    if (!employeeEmail) return true; // no filter
    if (!assignment || !assignment.email) return false;
    return assignment.email === employeeEmail;
};

function calculatePlanAndActual(
    tasksArray,
    startYearTimestamp,
    endYearTimestamp,
    project_id
) {
    project_id = project_id || "";

    var monthNames = [
        "January", "February", "March", "April", "May", "June",
        "July", "August", "September", "October", "November", "December"
    ];

    var monthlyData = [];

    // INIT 12 MONTHS
    for (var i = 0; i < 12; i++) {
        monthlyData.push({
            name: monthNames[i],
            month: i,

            estimatedManhours: 0,
            actualManhours: 0,

            // PLAN (hours)
            se_estimate_hours: 0,
            ui_se_estimate_hours: 0,
            devops_estimate_hours: 0,
            qa_estimate_hours: 0,
            sa_estimate_hours: 0,

            // ACTUAL (hours)
            se_actual_hours: 0,
            ui_se_actual_hours: 0,
            devops_actual_hours: 0,
            qa_actual_hours: 0,
            sa_actual_hours: 0,

            plan: 0,
            actual: 0,

            summary: {
                solution_engineer: { plan: 0, actual: 0 },
                ui_solution_engineer: { plan: 0, actual: 0 },
                devops: { plan: 0, actual: 0 },
                quality_assurance: { plan: 0, actual: 0 },
                system_analyst: { plan: 0, actual: 0 }
            }
        });
    }

    // LOOP TASKS
    for (var i = 0; i < tasksArray.length; i++) {
        var task = tasksArray[i];
        var createdAt = task.created_at;

        if (!createdAt || createdAt < startYearTimestamp || createdAt >= endYearTimestamp) {
            continue;
        }

        if (project_id) {
            var pid = task.company_project ? task.company_project.id : "";
            if (pid !== project_id) continue;
        }

        var month = new Date(createdAt).getMonth();
        var unit = task.company_unit ? task.company_unit.name : "";

        // PLAN (ESTIMATE)
        if (typeof task.estimate_manhour === "number") {

            // Solution Engineer
            if (unit === "Solution Engineer") {
                monthlyData[month].se_estimate_hours += task.estimate_manhour;
                monthlyData[month].estimatedManhours += task.estimate_manhour;
            }

            // UI Solution Engineer
            if (unit === "UI Solution Engineer") {
                monthlyData[month].ui_se_estimate_hours += task.estimate_manhour;
                monthlyData[month].estimatedManhours += task.estimate_manhour;
            }

            // DevOps
            if (unit === "Devops") {
                monthlyData[month].devops_estimate_hours += task.estimate_manhour;
                monthlyData[month].estimatedManhours += task.estimate_manhour;
            }
        }

        // System Analyst
        if (typeof task.estimate_manhour_sa === "number") {
            monthlyData[month].sa_estimate_hours += task.estimate_manhour_sa;
            monthlyData[month].estimatedManhours += task.estimate_manhour_sa;
        }

        // QA 
        if (typeof task.estimate_manhour_qa === "number") {
            monthlyData[month].qa_estimate_hours += task.estimate_manhour_qa;
        }

        // ACTUAL
        if (task.dev_timer && typeof task.dev_timer.duration === "number") {
            var actualHours = task.dev_timer.duration / 3600000;

            // Solution Engineer
            if (unit === "Solution Engineer") {
                monthlyData[month].se_actual_hours += actualHours;
                monthlyData[month].actualManhours += actualHours;
            }

            // UI Solution Engineer
            if (unit === "UI Solution Engineer") {
                monthlyData[month].ui_se_actual_hours += actualHours;
                monthlyData[month].actualManhours += actualHours;
            }

            // DevOps
            if (unit === "Devops") {
                monthlyData[month].devops_actual_hours += actualHours;
                monthlyData[month].actualManhours += actualHours;
            }
        }

        // System Analyst actual
        if (task.sa_timer && typeof task.sa_timer.duration === "number") {
            var saHours = task.sa_timer.duration / 3600000;
            monthlyData[month].sa_actual_hours += saHours;
            monthlyData[month].actualManhours += saHours;
        }

        // QA actual
        if (task.qa_timer && typeof task.qa_timer.duration === "number") {
            monthlyData[month].qa_actual_hours += task.qa_timer.duration / 3600000;
        }
    }

    // CONVERT TO MANDAYS
    function round2(n) {
        return Math.round(n * 100) / 100;
    }

    for (var i = 0; i < 12; i++) {
        var m = monthlyData[i];

        m.plan = round2(m.estimatedManhours / 8);
        m.actual = round2(m.actualManhours / 8);

        m.summary.solution_engineer.plan = round2(m.se_estimate_hours / 8);
        m.summary.solution_engineer.actual = round2(m.se_actual_hours / 8);

        m.summary.ui_solution_engineer.plan = round2(m.ui_se_estimate_hours / 8);
        m.summary.ui_solution_engineer.actual = round2(m.ui_se_actual_hours / 8);

        m.summary.devops.plan = round2(m.devops_estimate_hours / 8);
        m.summary.devops.actual = round2(m.devops_actual_hours / 8);

        m.summary.system_analyst.plan = round2(m.sa_estimate_hours / 8);
        m.summary.system_analyst.actual = round2(m.sa_actual_hours / 8);

        m.summary.quality_assurance.plan = round2(m.qa_estimate_hours / 8);
        m.summary.quality_assurance.actual = round2(m.qa_actual_hours / 8);
    }

    return monthlyData;
};


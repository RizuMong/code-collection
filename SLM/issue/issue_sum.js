function calculateEstimatedManhoursByProject(tasksArray, projectsArray) {
    // Objects to store aggregated estimated man-hours per role by project ID
    var aggregatedManhoursSE = {}; // Solution Engineer (Estimated)
    var aggregatedManhoursCX = {}; // Customer Experience (Estimated)
    var aggregatedManhoursQA = {}; // Quality Assurance (Estimated)
    var aggregatedManhoursSA = {}; // System Analyst (Estimated)

    // Objects to store aggregated actual man-hours per role by project ID (from timers)
    var aggregatedActualManhoursDev = {}; // Developer (Actual from dev_timer)
    var aggregatedActualManhoursSA = {}; // System Analyst (Actual from sa_timer)
    var aggregatedActualManhoursQA = {}; // Quality Assurance (Actual from qa_timer)

    // Objects to store aggregated task counts by status by project ID
    var aggregatedTotaltask = {};
    var aggregatedTotaltaskBacklog = {};
    var aggregatedTotaltaskInProgress = {};
    var aggregatedTotaltaskWaitingQA = {};
    var aggregatedTotaltaskQATesting = {};
    var aggregatedTotaltaskBug = {};
    var aggregatedTotaltaskDone = {};
    var aggregatedTotaltaskCancel = {};
    var aggregatedTotaltaskArchived = {};
    var aggregatedTotaltaskMove = {};

    // First pass: Aggregate data from the tasksArray.
    // Loop through each task to sum man-hours and count tasks by status for each project.
    for (var i = 0; i < tasksArray.length; i++) {
        var task = tasksArray[i];
        var projectId = task.company_project && task.company_project.id;
        var taskStatus = task.status && task.status.name;

        // Ensure task has a valid project ID before processing
        if (projectId) {
            // Aggregate Estimated Man-hours per role
            if (typeof task.estimate_manhour === 'number') {
                aggregatedManhoursSE[projectId] = (aggregatedManhoursSE[projectId] || 0) + task.estimate_manhour;
            }
            if (typeof task.estimate_manhour_cx === 'number') {
                aggregatedManhoursCX[projectId] = (aggregatedManhoursCX[projectId] || 0) + task.estimate_manhour_cx;
            }
            if (typeof task.estimate_manhour_qa === 'number') {
                aggregatedManhoursQA[projectId] = (aggregatedManhoursQA[projectId] || 0) + task.estimate_manhour_qa;
            }
            if (typeof task.estimate_manhour_sa === 'number') {
                aggregatedManhoursSA[projectId] = (aggregatedManhoursSA[projectId] || 0) + task.estimate_manhour_sa;
            }

            // Aggregate Actual Man-hours per role (from timers)
            // dev_timer.duration is in milliseconds, convert to hours (divide by 1000 * 60 * 60)
            if (task.dev_timer && typeof task.dev_timer.duration === 'number') {
                var devHours = task.dev_timer.duration / (1000 * 60 * 60);
                aggregatedActualManhoursDev[projectId] = (aggregatedActualManhoursDev[projectId] || 0) + devHours;
            }
            // Assuming sa_timer.duration and qa_timer.duration follow similar structure and units
            if (task.sa_timer && typeof task.sa_timer.duration === 'number') {
                var saHours = task.sa_timer.duration / (1000 * 60 * 60);
                aggregatedActualManhoursSA[projectId] = (aggregatedActualManhoursSA[projectId] || 0) + saHours;
            }
            if (task.qa_timer && typeof task.qa_timer.duration === 'number') {
                var qaHours = task.qa_timer.duration / (1000 * 60 * 60);
                aggregatedActualManhoursQA[projectId] = (aggregatedActualManhoursQA[projectId] || 0) + qaHours;
            }


            // Aggregate total tasks for the project
            aggregatedTotaltask[projectId] = (aggregatedTotaltask[projectId] || 0) + 1;

            // Aggregate tasks by status
            if (taskStatus) {
                switch (taskStatus) {
                    case "Backlog":
                        aggregatedTotaltaskBacklog[projectId] = (aggregatedTotaltaskBacklog[projectId] || 0) + 1;
                        break;
                    case "In Progress":
                        aggregatedTotaltaskInProgress[projectId] = (aggregatedTotaltaskInProgress[projectId] || 0) + 1;
                        break;
                    case "Waiting QA":
                        aggregatedTotaltaskWaitingQA[projectId] = (aggregatedTotaltaskWaitingQA[projectId] || 0) + 1;
                        break;
                    case "QA Testing":
                        aggregatedTotaltaskQATesting[projectId] = (aggregatedTotaltaskQATesting[projectId] || 0) + 1;
                        break;
                    case "Bug":
                        aggregatedTotaltaskBug[projectId] = (aggregatedTotaltaskBug[projectId] || 0) + 1;
                        break;
                    case "Done":
                        aggregatedTotaltaskDone[projectId] = (aggregatedTotaltaskDone[projectId] || 0) + 1;
                        break;
                    case "Cancel":
                        aggregatedTotaltaskCancel[projectId] = (aggregatedTotaltaskCancel[projectId] || 0) + 1;
                        break;
                    case "Archived":
                        aggregatedTotaltaskArchived[projectId] = (aggregatedTotaltaskArchived[projectId] || 0) + 1;
                        break;
                    case "Move Next Sprint":
                        aggregatedTotaltaskMove[projectId] = (aggregatedTotaltaskMove[projectId] || 0) + 1;
                        break;
                    // Add more cases for other statuses if needed
                }
            }
        }
    }

    // Second pass: Iterate through projectsArray and add the aggregated data.
    // Loop through each project object in the projectsArray.
    for (var j = 0; j < projectsArray.length; j++) {
        var project = projectsArray[j];
        var projectId = project.id_company_project;

        // Check if the project has an id_company_project to match with aggregated data.
        if (projectId) {
            // Retrieve aggregated estimated man-hours for each role, defaulting to 0 if not found.
            var totalManhourSE = aggregatedManhoursSE[projectId] || 0;
            var totalManhourCX = aggregatedManhoursCX[projectId] || 0;
            var totalManhourQA = aggregatedManhoursQA[projectId] || 0;
            var totalManhourSA = aggregatedManhoursSA[projectId] || 0;

            // Retrieve aggregated actual man-hours for each role, defaulting to 0 if not found.
            var actualManhourDev = aggregatedActualManhoursDev[projectId] || 0;
            var actualManhourSA = aggregatedActualManhoursSA[projectId] || 0;
            var actualManhourQA = aggregatedActualManhoursQA[projectId] || 0;

            // Retrieve aggregated task counts for each status, defaulting to 0 if not found.
            var allTotalTask = aggregatedTotaltask[projectId] || 0;
            var totalTasksBacklog = aggregatedTotaltaskBacklog[projectId] || 0;
            var totalTasksInProgress = aggregatedTotaltaskInProgress[projectId] || 0;
            var totalTasksWaitingQA = aggregatedTotaltaskWaitingQA[projectId] || 0;
            var totalTasksQATesting = aggregatedTotaltaskQATesting[projectId] || 0;
            var totalTasksBug = aggregatedTotaltaskBug[projectId] || 0;
            var totalTasksDone = aggregatedTotaltaskDone[projectId] || 0;
            var totalTasksCancel = aggregatedTotaltaskCancel[projectId] || 0;
            var totalTasksArchived = aggregatedTotaltaskArchived[projectId] || 0;
            var totalTasksMove = aggregatedTotaltaskMove[projectId] || 0;

            // Helper function to round to 2 decimal places
            function roundToTwoDecimals(num) {
                return Math.round(num * 100) / 100;
            }

            // Add estimated man-days per role (assuming 8 hours per man-day)
            project.totalEstimatedMandaysSE = roundToTwoDecimals(totalManhourSE / 8);
            project.totalEstimatedMandaysCX = roundToTwoDecimals(totalManhourCX / 8);
            project.totalEstimatedMandaysQA = roundToTwoDecimals(totalManhourQA / 8);
            project.totalEstimatedMandaysSA = roundToTwoDecimals(totalManhourSA / 8);

            // Calculate total estimated man-days across all roles
            project.totalEstimatedMandays = roundToTwoDecimals(
                project.totalEstimatedMandaysSE +
                project.totalEstimatedMandaysCX +
                project.totalEstimatedMandaysQA +
                project.totalEstimatedMandaysSA
            );

            // Add actual man-days per role (assuming 8 hours per man-day)
            project.totalActualMandaysDev = roundToTwoDecimals(actualManhourDev / 8);
            project.totalActualMandaysSA = roundToTwoDecimals(actualManhourSA / 8);
            project.totalActualMandaysQA = roundToTwoDecimals(actualManhourQA / 8);

            // Calculate total actual man-days across all roles
            project.totalActualMandays = roundToTwoDecimals(
                project.totalActualMandaysDev +
                project.totalActualMandaysSA +
                project.totalActualMandaysQA
            );

            // Calculate total SOW (Sum of Work) from project's mandays_*_sow fields
            var totalSOW = (project.mandays_custom_product_sow || 0) +
                (project.mandays_customer_experience_sow || 0) +
                (project.mandays_infra_engineers_sow || 0) +
                (project.mandays_project_managers_sow || 0) +
                (project.mandays_quality_assurance_sow || 0) +
                (project.mandays_solution_engineers_sow || 0) +
                (project.mandays_system_analyst_sow || 0) +
                (project.mandays_tech_writer_sow || 0) +
                (project.mandays_ui_solution_engineers_sow || 0);

            // Add remaining mandays
            project.remaining_mandays = roundToTwoDecimals(totalSOW - project.totalActualMandays);

            //Mandays SOW VS Mandays SA (estimation)

            // Add total task count and task counts by status to the project object
            project.AlltotalTask = allTotalTask;
            project.totalTasksBacklog = totalTasksBacklog;
            project.totalTasksInProgress = totalTasksInProgress;
            project.totalTasksWaitingQA = totalTasksWaitingQA;
            project.totalTasksQATesting = totalTasksQATesting;
            project.totalTasksBug = totalTasksBug;
            project.totalTasksDone = totalTasksDone;
            project.totalTasksCancel = totalTasksCancel;
            project.totalTasksArchived = totalTasksArchived;
            project.totalTasksMove = totalTasksMove;
            project.totalSOW = totalSOW;
            project.SOW_vs_PlanSa = totalSOW / project.totalEstimatedMandays + '%'

        } else {
            // If a project in projectsArray doesn't have an id_company_project,
            // set all related metrics to 0.
            project.totalEstimatedMandaysSE = 0;
            project.totalEstimatedMandaysCX = 0;
            project.totalEstimatedMandaysQA = 0;
            project.totalEstimatedMandaysSA = 0;
            project.totalEstimatedMandays = 0;
            project.totalActualMandaysDev = 0;
            project.totalActualMandaysSA = 0;
            project.totalActualMandaysQA = 0;
            project.totalActualMandays = 0;
            project.remaining_mandays = 0; // Set remaining_mandays to 0 as well
            project.AlltotalTask = 0;
            project.totalTasksBacklog = 0;
            project.totalTasksInProgress = 0;
            project.totalTasksWaitingQA = 0;
            project.totalTasksQATesting = 0;
            project.totalTasksBug = 0;
            project.totalTasksDone = 0;
            project.totalTasksCancel = 0;
            project.totalTasksArchived = 0;
            project.totalTasksMove = 0;
            project.totalSOW = 0;
        }
    }

    // Return the modified projectsArray.
    return projectsArray;
}

